#!/usr/bin/env python3
"""
Snakes & Ladders — Offline Pack Bundler (Zero Dependencies)

Reads packs/manifest.json and all registered packs/*.json files, then writes
scenarios.js with window.GCP_MANIFEST and window.GCP_PACKS so the game works
offline via file:// as well as over HTTP fetch().

Usage:
    python3 scripts/bundle_packs.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST_PATH = ROOT / "packs" / "manifest.json"
OUTPUT_PATH = ROOT / "scenarios.js"


def main() -> int:
    if not MANIFEST_PATH.exists():
        print(f"[ERROR] Missing {MANIFEST_PATH}", file=sys.stderr)
        return 1

    manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    packs_map = {}

    for entry in manifest.get("packs", []):
        pack_id = entry["id"]
        pack_file = ROOT / entry["file"]
        if not pack_file.exists():
            print(f"[ERROR] Missing pack file: {pack_file}", file=sys.stderr)
            return 1
        packs_map[pack_id] = json.loads(pack_file.read_text(encoding="utf-8"))

    default_id = manifest.get("defaultPack", "cloud-architect")

    js_lines = [
        "/**",
        " * Snakes & Ladders — Pluggable Pack Bundle & Offline Fallback",
        " * Auto-generated by: python3 scripts/bundle_packs.py",
        " * Do not edit manually; edit JSON files in packs/ and re-run scripts/bundle_packs.py.",
        " */",
        "'use strict';",
        "",
        f"window.GCP_MANIFEST = {json.dumps(manifest, ensure_ascii=False)};",
        "",
        f"window.GCP_PACKS = {json.dumps(packs_map, ensure_ascii=False)};",
        "",
        f"window.GCP_DEFAULT_PACK = window.GCP_PACKS[{json.dumps(default_id)}];",
        "",
    ]

    OUTPUT_PATH.write_text("\n".join(js_lines), encoding="utf-8")
    print(f"[OK] Bundled {len(packs_map)} packs into {OUTPUT_PATH.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
